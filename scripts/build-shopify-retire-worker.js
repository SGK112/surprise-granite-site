#!/usr/bin/env node
/**
 * Build cloudflare/shopify-retire-worker.js — the Worker on store.surprisegranite.com/*.
 *
 * Two jobs, and the second one is why this generator exists:
 *
 * 1. Redirect old Shopify product URLs to their real home. The hand-built MAP from the
 *    Shopify export covers 2,712 handles, but the site now has ~7,500 product pages, and
 *    a 2026-08-07 GSC sample showed only 12% of crawled Shopify handles were in that MAP.
 *    So we ALSO index every product page on disk by slug — old Shopify handles and current
 *    page slugs agree far more often than the export did.
 *
 * 2. Return 410 Gone for everything genuinely retired. Previously every unmatched path
 *    301'd to a generic /marketplace/, which Google treats as a soft 404 — it keeps the URL
 *    in the index and keeps re-crawling it. Of the unmapped handles Google had crawled,
 *    97% had no page anywhere on the site: they are gone, and 410 says so.
 *
 * The 410 still serves a real HTML page with links, so a human following an old bookmark
 * lands somewhere useful; only the status code speaks to crawlers.
 *
 * The homepage keeps its 301 to /marketplace/ — it is the one URL on that host with real
 * equity and the one a human might actually type.
 *
 * Usage: node scripts/build-shopify-retire-worker.js [--write]
 * Deploy: see cloudflare/deploy-shopify-retire.sh
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const WORKER = path.join(ROOT, 'cloudflare', 'shopify-retire-worker.js');
const WRITE = process.argv.includes('--write');
const WWW = 'https://www.surprisegranite.com';

// Pull the existing hand-built MAP out of the current worker so we never lose it.
function existingMap() {
  const src = fs.readFileSync(WORKER, 'utf8');
  const start = src.indexOf('{', src.indexOf('MAP'));
  let depth = 0;
  for (let i = start; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return JSON.parse(src.slice(start, i + 1));
  }
  throw new Error('could not parse MAP out of ' + WORKER);
}

// Every product page that actually exists, indexed by its slug.
function pagesOnDisk() {
  const found = {};
  const walk = (rel) => {
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) return;
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name.startsWith('.')) continue;
      const childRel = path.join(rel, entry.name);
      if (fs.existsSync(path.join(ROOT, childRel, 'index.html'))) {
        found[entry.name.toLowerCase()] = `${WWW}/${childRel}/`;
      }
      walk(childRel);
    }
  };
  ['marketplace', 'countertops', 'flooring'].forEach(walk);
  return found;
}

const map = existingMap();
const before = Object.keys(map).length;
const disk = pagesOnDisk();
let added = 0;
for (const [slug, url] of Object.entries(disk)) {
  if (!map[slug]) { map[slug] = url; added++; }   // never override a curated entry
}

const body = `// Shopify retirement Worker — store.surprisegranite.com
//
// GENERATED by scripts/build-shopify-retire-worker.js — edit that, not this.
//
// Old Shopify handles 301 to their real page when we have one (${Object.keys(map).length} known
// handles: ${before} from the Shopify export + ${added} matched against pages on disk).
// Everything else 410s, because it is actually gone — a 301 to a generic category page
// reads as a soft 404 to Google and keeps the dead URL alive in the index forever.
//
// Route: store.surprisegranite.com/*  (Cloudflare Redirect Rules run BEFORE Workers, so a
// blanket redirect rule on this host will silently pre-empt everything below — see the
// disabled rule cb8467abf6ec on ruleset 8c6b31e52afc49f7bd562dbe20215bc7.)

const WWW = '${WWW}';
const MARKET = WWW + '/marketplace/';

const MAP = ${JSON.stringify(map)};

function r301(loc) {
  return new Response(null, {
    status: 301,
    headers: { 'Location': loc, 'Cache-Control': 'public, max-age=86400' },
  });
}

// 410 for crawlers, a usable page for humans.
function gone() {
  const html = '<!doctype html><html lang="en"><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width,initial-scale=1">' +
    '<meta name="robots" content="noindex">' +
    '<title>This page is no longer available | Surprise Granite</title>' +
    '<style>body{margin:0;padding:3rem 1.5rem;font:16px/1.6 system-ui,-apple-system,Segoe UI,sans-serif;' +
    'color:#1a1a1a;background:#fff}main{max-width:34rem;margin:0 auto}h1{font-size:1.5rem;margin:0 0 .75rem}' +
    'p{color:#555}ul{padding:0;margin:1.5rem 0 0;list-style:none}li{margin:0 0 .6rem}' +
    'a{color:#b8860b;font-weight:600;text-decoration:none}a:hover{text-decoration:underline}' +
    '@media(prefers-color-scheme:dark){body{background:#111;color:#f2f2f2}p{color:#aaa}}</style></head><body><main>' +
    '<h1>This page is no longer available</h1>' +
    '<p>Our old online store has closed. Everything we carry now lives on the main site.</p><ul>' +
    '<li><a href="' + MARKET + '">Browse the marketplace</a></li>' +
    '<li><a href="' + WWW + '/materials/all-countertops/">Countertop colors</a></li>' +
    '<li><a href="' + MARKET + 'sinks/">Sinks</a> &middot; <a href="' + MARKET + 'faucets/">Faucets</a> &middot; ' +
    '<a href="' + MARKET + 'tile/">Tile</a></li>' +
    '<li><a href="' + WWW + '/get-a-free-estimate/">Get a free estimate</a></li></ul></main></body></html>';
  return new Response(html, {
    status: 410,
    headers: { 'Content-Type': 'text/html;charset=UTF-8', 'Cache-Control': 'public, max-age=86400' },
  });
}

export default {
  async fetch(request) {
    const url = new URL(request.url);

    // Feeds are crawl bloat, never real pages.
    if (url.pathname.endsWith('.atom')) return gone();

    const seg = url.pathname.split('/').filter(Boolean);

    // A handle shows up as /products/<h> and also as /collections/<c>/products/<h>.
    const i = seg.indexOf('products');
    if (i !== -1 && seg[i + 1]) {
      const dest = MAP[decodeURIComponent(seg[i + 1]).toLowerCase()];
      return dest ? r301(dest) : gone();
    }

    // The storefront homepage is the one URL here worth keeping pointed at something.
    if (seg.length === 0) return r301(MARKET);

    // Collections, facets, feeds, llms.txt, everything else: retired.
    return gone();
  },
};
`;

console.log(`MAP: ${before} curated + ${added} matched from disk = ${Object.keys(map).length}`);
console.log(`worker: ${(body.length / 1024).toFixed(0)}KB uncompressed`);
if (WRITE) {
  fs.writeFileSync(WORKER, body);
  console.log(`wrote ${path.relative(ROOT, WORKER)}`);
} else {
  console.log('Dry run. Re-run with --write to apply.');
}
